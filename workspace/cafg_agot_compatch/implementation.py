#!/usr/bin/env python3
"""Rebase CaFG onto AGOT's culture, faith, MAA, and event databases.

Two mechanisms, chosen per content type because CK3 resolves them differently:

* `common/` databases resolve per object, LIOS by ASCIIbetical filename. Every
  repair there is emitted as a `zzz_cafg_agot_*` keyed override carrying only
  the objects that actually change, so a CaFG edit to any neighbouring object
  is picked up instead of being silently reverted.
* `events/` resolve whole-file, same path only, and duplicate event ids are an
  engine error rather than an override. Those files are produced by a three-way
  merge with vanilla as the common ancestor of CaFG and AGOT.

Every removal, merge resolution, and post-merge marker count is asserted so a
CaFG or AGOT update fails loudly instead of drifting.
"""

