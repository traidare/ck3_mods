def generate_tolerance_law_triggers(inputs: RunInputs) -> None:
    """Drop startup tolerance-law checks for AGOT's absent steppe tradition.

    AGOT replaces the culture database without `tradition_steppe_tolerance`, so
    each check fails `has_cultural_tradition` against a null target while CK3
    picks initial realm laws. Every surviving CaFG criterion is preserved.
    """
    cases = (
        (
            "culture",
            "            has_cultural_tradition = tradition_steppe_tolerance\n",
            (
                "T_kCAFG_should_start_with_intolerant_culture_law",
                "T_kCAFG_should_start_with_tolerant_culture_law",
            ),
        ),
        (
            "faith",
            "\t\tculture = { has_cultural_tradition = tradition_steppe_tolerance }\n",
            (
                "T_kCAFG_should_start_with_intolerant_faith_law",
                "T_kCAFG_should_start_with_tolerant_faith_law",
            ),
        ),
    )
    for kind, check, expected in cases:
        relative = f"common/scripted_triggers/kei_cafg_{kind}_laws_triggers.txt"
        source = read_text(inputs.MOD_SOURCE / relative)
        text = replace_exact(
            source,
            check,
            "",
            expected=2,
            label=f"CaFG AGOT {kind} tolerance-law steppe tradition",
        )
        if "tradition_steppe_tolerance" in text:
            raise RuntimeError(
                f"{relative} retains an AGOT-absent steppe-tolerance reference"
            )
        write_text(
            inputs,
            f"common/scripted_triggers/zzz_cafg_agot_{kind}_laws_triggers.txt",
            keyed_override(source, text, expected, relative),
            root=inputs.MOD_OUTPUT,
        )


