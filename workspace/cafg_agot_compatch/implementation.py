def generate_disabled_vanilla_overrides(inputs: RunInputs) -> None:
    """Blank CaFG files that reintroduce vanilla-only content AGOT disables.

    A single-object `common/` override can redefine an object but never remove
    one, and CK3 still parses the original file either way. An exact-path,
    intentionally empty override is the only mechanism that stops these
    definitions loading at all.
    """
    for relative, definitions, reason in DISABLED_VANILLA_FILES:
        source = read_text(inputs.MOD_SOURCE / relative)
        for definition in definitions:
            found = source.count(f"{definition} = {{")
            if found != 1:
                raise RuntimeError(
                    f"CaFG vanilla-only override {relative}: expected one "
                    f"{definition} definition, found {found}"
                )
        body = "".join(f"# {line}\n".rstrip(" ") for line in reason.split("\n"))
        write_text(
            inputs,
            relative,
            "# AGOT compatibility: intentionally empty.\n#\n" + body,
            root=inputs.MOD_OUTPUT,
        )


