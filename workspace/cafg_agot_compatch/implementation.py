def read_text(path: Path) -> str:
    return read_source(path, normalize_newlines=True)


def write_text(
    inputs: RunInputs, relative: str, text: str, *, root: Path | None = None
) -> None:
    path = (inputs.OUTPUT if root is None else root) / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8-sig", newline="\n")


def top_level_definitions(text: str) -> tuple[dict[str, str], list[str]]:
    """Split a `common/` database file into its column-zero definitions."""
    bodies: dict[str, str] = {}
    order: list[str] = []
    for match in re.finditer(r"(?m)^([A-Za-z0-9_]+)\s*=\s*\{", text):
        name = match.group(1)
        if name in bodies:
            raise RuntimeError(f"duplicate definition {name} in source file")
        opening = text.index("{", match.start())
        bodies[name] = text[match.start() : matching_brace(text, opening) + 1]
        order.append(name)
    return bodies, order


def keyed_override(
    source: str, rebased: str, expected: tuple[str, ...], relative: str
) -> str:
    """Emit only the definitions the rebase actually changed.

    Asserting the changed set means a CaFG release that edits one of these
    objects — or stops needing the repair — fails generation rather than being
    silently overridden by a stale copy.
    """
    source_bodies, order = top_level_definitions(source)
    rebased_bodies, _ = top_level_definitions(rebased)
    if set(source_bodies) != set(rebased_bodies):
        raise RuntimeError(
            f"{relative}: rebase added or removed top-level definitions: "
            f"{sorted(set(source_bodies) ^ set(rebased_bodies))}"
        )

    changed = tuple(
        name for name in order if source_bodies[name] != rebased_bodies[name]
    )
    if changed != expected:
        raise RuntimeError(
            f"{relative}: expected the rebase to change {list(expected)}, "
            f"changed {list(changed)}"
        )

    header = KEYED_HEADER.format(source=relative, count=len(changed))
    return header + "".join(f"\n{rebased_bodies[name]}\n" for name in changed)


CONFLICT = re.compile(
    r"(?ms)^<<<<<<< ours\n(?P<ours>.*?)"
    r"^\|\|\|\|\|\|\| base\n(?P<base>.*?)"
    r"^=======\n(?P<theirs>.*?)"
    r"^>>>>>>> theirs\n"
)


def merge_three_way(base: str, ours: str, theirs: str) -> str:
    """Merge CaFG and AGOT over their common vanilla ancestor.

    Both parents edit vanilla independently, so vanilla is the correct merge
    base: a hunk only conflicts where CaFG and AGOT changed the same vanilla
    lines, which is exactly the set a human has to rule on.
    """
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        files = {"ours": ours, "base": base, "theirs": theirs}
        for name, text in files.items():
            (root / name).write_text(text, encoding="utf-8", newline="\n")
        result = subprocess.run(
            [
                "git",
                "merge-file",
                "--diff3",
                "-p",
                "-L",
                "ours",
                "-L",
                "base",
                "-L",
                "theirs",
                str(root / "ours"),
                str(root / "base"),
                str(root / "theirs"),
            ],
            capture_output=True,
            text=True,
        )
    if result.returncode < 0:
        raise RuntimeError(f"git merge-file failed: {result.stderr.strip()}")
    return result.stdout


def take_agot_disabled(ours: str, theirs: str, label: str) -> str:
    """Resolve a hunk AGOT disabled wholesale by commenting it out.

    CaFG only hooked into code AGOT no longer runs, so keeping CaFG's side
    would reintroduce an event chain AGOT deliberately removed.
    """
    if not ours.strip():
        raise RuntimeError(f"{label}: CaFG side is empty, resolution no longer applies")
    live = [
        line
        for line in theirs.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    if live:
        raise RuntimeError(
            f"{label}: AGOT no longer disables this block; "
            f"{len(live)} live line(s) remain, first: {live[0].strip()!r}"
        )
    return theirs


def combine_domain_conversion(ours: str, theirs: str, label: str) -> str:
    """Keep CaFG's granular conversion but convert to AGOT's chosen culture.

    AGOT retargets `stewardship_domain.1073` from the ruler's own culture to
    `scope:new_culture`. Taking either side alone loses one of the two changes.
    """
    if "set_county_culture = scope:new_culture" not in theirs:
        raise RuntimeError(f"{label}: AGOT no longer retargets to scope:new_culture")
    rebased = replace_exact(
        ours,
        "CULTURE = root.culture",
        "CULTURE = scope:new_culture",
        expected=1,
        label=label,
    )
    # Keep AGOT's own annotation and its commented-out original above the
    # replacement, so the merged file still records why the target changed.
    annotation = "".join(
        f"{line}\n" for line in theirs.splitlines() if line.lstrip().startswith("#")
    )
    return annotation + rebased


def maa_type(line: str) -> str | None:
    match = MAA_CALL.search(line)
    return match.group(1) if match else None


def script_brace_delta(line: str) -> int:
    """Count structural braces, excluding comments and quoted strings."""
    code = line.split("#", 1)[0]
    code = re.sub(r'"(?:\\.|[^"\\])*"', '""', code)
    return code.count("{") - code.count("}")


def weighted_branch(lines: list[str], marker: int) -> tuple[int, int]:
    start = next(
        (
            index
            for index in range(marker, -1, -1)
            if WEIGHTED_BRANCH.match(lines[index].rstrip("\r\n"))
        ),
        None,
    )
    if start is None:
        raise RuntimeError(
            f"CaFG cultural benefit at source line {marker + 1} "
            "has no enclosing weighted branch"
        )

    depth = 0
    for end in range(start, len(lines)):
        depth += script_brace_delta(lines[end])
        if depth == 0:
            if end < marker:
                break
            return start, end + 1
    raise RuntimeError(f"CaFG weighted branch at source line {start + 1} is unbalanced")


def generate_boons(inputs: RunInputs) -> None:
    relative = "common/scripted_effects/kei_cafg_cultural_boons_effects.txt"
    source = read_text(inputs.MOD_SOURCE / relative)
    lines = source.splitlines(keepends=True)
    removed = Counter()
    output: list[str] = []

    for line in lines:
        identifier = maa_type(line)
        if identifier in INVALID_MAA_TYPES:
            removed[identifier] += 1
            continue
        output.append(line)

    expected = {
        "bondi",
        "cataphract",
        "huscarl",
        "varangian_guards",
        "varangian_veterans",
        "vigmen",
    }
    if set(removed) != expected or sum(removed.values()) != 6:
        raise RuntimeError(
            "CaFG cultural-boon helpers: expected six removed MAA calls "
            f"for {sorted(expected)}, found {dict(removed)}"
        )

    text = "".join(output)
    text = replace_exact(
        text,
        """                random_list = {
                    150 = {}
                    50 = {
                        trigger = { NOT = { religion = religion:islam_religion } }
                        add_trait = pilgrim
                    }
                    50 = {
                        trigger = { religion = religion:islam_religion }
                        add_trait = hajjaj
                    }
                }""",
        "                add_trait = pilgrim",
        expected=1,
        label="CaFG AGOT pilgrimage trait",
    )
    text = replace_exact(
        text,
        """            if = {
                limit = { NOT = { knows_language_of_culture = culture:han } }
                learn_language_of_culture = culture:han
            }
            if = {
                limit = { NOT = { has_trait = confucian_education } }
                add_trait = confucian_education
            }
            add_trait_xp = {
                trait = confucian_education
                value = {
                    integer_range = {
                        min = small_lifestyle_random_xp_low
                        max = medium_lifestyle_random_xp_high
                    }
                }
            }
""",
        "",
        expected=1,
        label="CaFG AGOT scholar-official vanilla trait and language",
    )
    text = replace_exact(
        text,
        (
            'CONDITION = "OR = { terrain = plains terrain = steppe '
            'geographical_region = world_steppe }"'
        ),
        'CONDITION = "OR = { terrain = plains terrain = steppe }"',
        expected=1,
        label="CaFG AGOT pastoralist geographical region",
    )
    remaining_invalid = {
        identifier
        for identifier in MAA_CALL.findall(text)
        if identifier in INVALID_MAA_TYPES
    }
    if remaining_invalid:
        raise RuntimeError(
            "CaFG cultural-boon helpers still reference invalid MAA types: "
            f"{sorted(remaining_invalid)}"
        )
    write_text(
        inputs,
        "common/scripted_effects/zzz_cafg_agot_cultural_boons_effects.txt",
        keyed_override(
            source,
            text,
            (
                "E_kCAFG_cultural_boon_tradition_warrior_monks",
                "E_kCAFG_cultural_boon_tradition_pastoralists",
                "E_kCAFG_cultural_boon_tradition_fp1_coastal_warriors",
                "E_kCAFG_cultural_boon_tradition_ep3_imperial_tagmata",
                "E_kCAFG_cultural_boon_tradition_ep3_palace_politics",
                "E_kCAFG_cultural_boon_tradition_scholar_officials",
            ),
            relative,
        ),
        root=inputs.MOD_OUTPUT,
    )


def generate_benefits(inputs: RunInputs) -> None:
    relative = "common/scripted_effects/kei_cafg_cultural_benefits_effects.txt"
    source = read_text(inputs.MOD_SOURCE / relative)
    lines = source.splitlines(keepends=True)
    invalid_calls = Counter()
    markers: list[int] = []

    for index, line in enumerate(lines):
        identifier = maa_type(line)
        if identifier in INVALID_MAA_TYPES:
            invalid_calls[identifier] += 1
            markers.append(index)
        if any(
            tradition in INVALID_TRADITIONS
            for tradition in TRADITION_CHECK.findall(line)
        ):
            markers.append(index)

    if set(invalid_calls) != INVALID_MAA_TYPES - {
        "bondi",
        "cataphract",
        "varangian_guards",
        "varangian_veterans",
        "vigmen",
    }:
        raise RuntimeError(
            f"CaFG cultural-benefit invalid MAA set changed: {dict(invalid_calls)}"
        )
    if sum(invalid_calls.values()) != 30:
        raise RuntimeError(
            "CaFG cultural benefits: expected 30 invalid MAA calls, "
            f"found {sum(invalid_calls.values())}"
        )

    helper_markers = [
        index for index, line in enumerate(lines) if COASTAL_HELPER_CALL in line
    ]
    if len(helper_markers) != 1:
        raise RuntimeError(
            "CaFG coastal-warriors helper: expected one caller, found "
            f"{len(helper_markers)}"
        )
    markers.extend(helper_markers)

    if len(markers) != 42:
        raise RuntimeError(
            "CaFG cultural benefits: expected 42 invalid branch markers, "
            f"found {len(markers)}"
        )
    branches = {weighted_branch(lines, marker) for marker in markers}
    if len(branches) != 41:
        raise RuntimeError(
            "CaFG cultural benefits: expected 41 removed weighted branches, "
            f"found {len(branches)}"
        )

    for start, end in sorted(branches, reverse=True):
        del lines[start:end]

    text = "".join(lines)
    text = replace_exact(
        text,
        "\t\t\t\t\t\tgeographical_region = world_steppe\n",
        "",
        expected=1,
        label="CaFG AGOT pastoralist benefit geographical region",
    )
    remaining_invalid = {
        identifier
        for identifier in MAA_CALL.findall(text)
        if identifier in INVALID_MAA_TYPES
    }
    remaining_traditions = {
        tradition
        for tradition in TRADITION_CHECK.findall(text)
        if tradition in INVALID_TRADITIONS
    }
    if remaining_invalid or remaining_traditions or COASTAL_HELPER_CALL in text:
        raise RuntimeError(
            "CaFG cultural benefits retain an invalid database branch: "
            f"MAA={sorted(remaining_invalid)}, "
            f"traditions={sorted(remaining_traditions)}"
        )
    write_text(
        inputs,
        "common/scripted_effects/zzz_cafg_agot_cultural_benefits_effects.txt",
        keyed_override(source, text, ("E_kCAFG_apply_random_cultural_boon",), relative),
        root=inputs.MOD_OUTPUT,
    )


