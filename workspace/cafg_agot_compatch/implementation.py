def generate_county_view(inputs: RunInputs, source_root: Path, label: str) -> None:
    """Re-apply CaFG's two county-view hooks on top of another mod's window.

    `gui/window_*.gui` overrides whole-file and same-path only, so the compatch
    has to ship a complete copy. CaFG's entire delta is two `using` lines — the
    widgets themselves live in its own template file, which loads normally — so
    the copy is generated rather than hand-maintained.
    """
    for template in (
        "kCAFG_County_View_States",
        "kCAFG_Province_View_Additional_Buttons",
    ):
        defined = read_text(inputs.MOD_SOURCE / CAFG_GUI_TEMPLATES)
        if f"template {template}" not in defined:
            raise RuntimeError(
                f"CaFG no longer defines {template} in {CAFG_GUI_TEMPLATES}"
            )

    text = read_text(source_root / COUNTY_VIEW)
    text = replace_exact(
        text,
        COUNTY_VIEW_STATES_ANCHOR,
        "\talwaystransparent = yes\n\n"
        "\tusing = kCAFG_County_View_States\n\n"
        "\tvbox = {\n",
        expected=1,
        label=f"{label} county-view states anchor",
    )
    text = replace_exact(
        text,
        PROVINCE_BUTTONS_ANCHOR,
        PROVINCE_BUTTONS_ANCHOR.removesuffix("\t\t\t}\n")
        + "\t\t\tusing = kCAFG_Province_View_Additional_Buttons\n"
        + "\t\t\t}\n",
        expected=1,
        label=f"{label} province-view buttons anchor",
    )
    write_text(inputs, COUNTY_VIEW, text, root=inputs.MOD_OUTPUT)


