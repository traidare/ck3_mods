def merge_event_file(inputs: RunInputs, merge: EventMerge, label: str = "AGOT") -> None:
    """Merge one CaFG event file onto the parent named by ``AGOT_SOURCE``.

    The LoV variant reuses this with LoV RC71 as the parent, so the merge
    strategy and conflict resolutions cannot drift between the two items.
    """
    base = read_text(inputs.VANILLA_SOURCE / merge.relative)
    ours = read_text(inputs.MOD_SOURCE / merge.relative)
    theirs = read_text(inputs.AGOT_SOURCE / merge.relative)
    merged = merge_three_way(base, ours, theirs)

    hunks = list(CONFLICT.finditer(merged))
    if len(hunks) != len(merge.resolutions):
        raise RuntimeError(
            f"{label} {merge.relative}: expected {len(merge.resolutions)} merge "
            f"conflict(s), found {len(hunks)}"
        )
    for index, hunk in reversed(list(enumerate(hunks))):
        name = merge.resolutions[index]
        hunk_label = f"{label} {merge.relative} hunk {index + 1} ({name})"
        resolved = RESOLVERS[name](hunk.group("ours"), hunk.group("theirs"), hunk_label)
        merged = merged[: hunk.start()] + resolved + merged[hunk.end() :]

    if "<<<<<<<" in merged or ">>>>>>>" in merged:
        raise RuntimeError(f"{label} {merge.relative}: unresolved conflict marker")

    calls = len(CAFG_CALL.findall(merged))
    markers = len(AGOT_MARKER.findall(merged))
    if (calls, markers) != (merge.cafg_calls, merge.agot_markers):
        raise RuntimeError(
            f"{label} {merge.relative}: expected {merge.cafg_calls} CaFG call(s) "
            f"and {merge.agot_markers} AGOT marker(s), merged output has "
            f"{calls} and {markers}"
        )
    write_text(inputs, merge.relative, merged, root=inputs.MOD_OUTPUT)


def generate_event_merges(inputs: RunInputs) -> None:
    """Rebuild every CaFG event hook on top of AGOT's current event files.

    `events/` override whole-file and same-path only — CK3 rejects a duplicate
    event id outright — so each of these files has to carry AGOT's complete
    text. Merging instead of hand-editing means an AGOT release lands here
    automatically, and the marker counts fail the build if it does not.
    """
    for merge in EVENT_MERGES:
        merge_event_file(inputs, merge)


