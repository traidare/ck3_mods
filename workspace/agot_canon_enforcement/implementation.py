#!/usr/bin/env python3
"""Generate the keyed redefinitions and the canon dragon taming fallback.

Two definitions live in `common/`, which resolves per key by ASCIIbetical
filename, so both are emitted into `zzzz_` files that win the key without
shadowing the neighbouring definitions their source files also carry.

The canon dragon outputs are additive instead. They read the dated
`agot_tame_dragon` entries in AGOT's dragon history — the only static record of
which rider bonded which dragon on which day — and emit a date-gated fallback
for the records AGOT's own tenth-birthday dispatch cannot reach.

The remaining sources are assertion-only: they pin the upstream markers this
module's runtime behaviour depends on, so a parent that renames or reworks one
fails generation instead of quietly disabling protection.
"""

